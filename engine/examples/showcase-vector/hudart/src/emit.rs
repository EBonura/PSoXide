//! Writes the generated Rust data file and the cellcheck layout.

use std::fmt::Write as _;

use crate::art::{
    self, bands, cap_palette, CAP_GLASS, cell_palette, clut, emblem_palette, gem_palette, Tone, ATLAS_POS,
    ATLAS_W, HORIZON, ZENITH,
};

/// CLUTs per stance, in this order, then the two gem CLUTs.
pub const CLUT_NAMES: [&str; 7] = [
    "FRONT_CELL_LIT",
    "FRONT_CELL_EMPTY",
    "FRONT_CAP",
    "BACK_CELL_LIT",
    "BACK_CELL_EMPTY",
    "BACK_CAP",
    "EMBLEM",
];

fn stance_colours() -> [(Tone, Tone, [u8; 3], [u8; 3]); 2] {
    [
        (Tone::front(HORIZON), Tone::back(HORIZON), HORIZON, ZENITH),
        (Tone::front(ZENITH), Tone::back(ZENITH), ZENITH, HORIZON),
    ]
}

/// Every CLUT in table order.
pub fn cluts() -> Vec<[u16; 16]> {
    let mut v = Vec::new();
    for (front, back, active, other) in stance_colours() {
        v.push(clut(&cell_palette(front, true), &[]));
        v.push(clut(&cell_palette(front, false), &[]));
        v.push(clut(&cap_palette(front), &CAP_GLASS));
        v.push(clut(&cell_palette(back, true), &[]));
        v.push(clut(&cell_palette(back, false), &[]));
        v.push(clut(&cap_palette(back), &CAP_GLASS));
        v.push(clut(&emblem_palette(active, other), &[]));
    }
    v.push(clut(&gem_palette(true), &[]));
    v.push(clut(&gem_palette(false), &[]));
    v
}

/// The generated data module (to be `include!`d next to the types it uses).
pub fn art_module() -> String {
    let mut s = String::new();
    s.push_str(
        "// @generated by showcase-vector/hudart (`cargo run -p hudart`). Do not edit by hand.\n\n",
    );
    for (name, v) in [
        ("COUNT", art::COUNT as i32),
        ("PITCH", art::PITCH),
        ("BAR_H", art::BAR_H),
        ("BAR_X0", art::BAR_X0),
        ("CAP_X", art::CAP_X),
        ("BACK_OFFSET", art::BACK_OFFSET),
        ("FRONT_Y", art::FRONT_Y),
        ("CELL_X0", art::CELL_X0),
        ("CELL_ROW", art::CELL_ROW),
        ("EMBLEM_X", art::EMBLEM_POS.0),
        ("EMBLEM_Y", art::EMBLEM_POS.1),
        ("GEM_X0", art::GEM_X0),
        ("GEM_Y", art::GEM_Y),
        ("CANVAS_W", art::CANVAS.0),
        ("CANVAS_H", art::CANVAS.1),
        ("CAP_W", art::CAP_W as i32),
    ] {
        let _ = writeln!(s, "pub const {name}: i32 = {v};");
    }
    let _ = writeln!(s, "\npub const ATLAS_HW_W: usize = {};", ATLAS_W / 4);
    let _ = writeln!(s, "pub const ATLAS_H: usize = {};", art::ATLAS_H);
    let atlas = art::atlas_halfwords();
    let _ = writeln!(
        s,
        "/// 4-bit texels, four per halfword, leftmost in the low nibble."
    );
    let _ = writeln!(s, "pub static ATLAS: [u16; {}] = [", atlas.len());
    for row in atlas.chunks(ATLAS_W / 4) {
        let line: Vec<String> = row.iter().map(|w| format!("0x{w:04x}")).collect();
        let _ = writeln!(s, "    {},", line.join(", "));
    }
    let _ = writeln!(s, "];\n");
    for ((name, sprite), (_, (u, v))) in art::sprites().iter().zip(ATLAS_POS.iter()) {
        let _ = writeln!(
            s,
            "pub const SPRITE_{name}: SpriteRect = SpriteRect {{ u: {u}, v: {v}, w: {}, h: {} }};",
            sprite.w, sprite.h
        );
    }
    let table = cluts();
    let _ = writeln!(s, "\npub const CLUT_COUNT: usize = {};", table.len());
    let _ = writeln!(
        s,
        "pub const CLUTS_PER_STANCE: usize = {};",
        CLUT_NAMES.len()
    );
    for (i, name) in CLUT_NAMES.iter().enumerate() {
        let _ = writeln!(s, "pub const CLUT_{name}: usize = {i};");
    }
    let _ = writeln!(
        s,
        "pub const CLUT_GEM_LIT: usize = {};",
        2 * CLUT_NAMES.len()
    );
    let _ = writeln!(
        s,
        "pub const CLUT_GEM_EMPTY: usize = {};",
        2 * CLUT_NAMES.len() + 1
    );
    let _ = writeln!(
        s,
        "/// 15-bit CLUT entries, 16 per CLUT in table order, entry 0 of each transparent."
    );
    let _ = writeln!(s, "pub static CLUTS: [u16; {}] = [", table.len() * 16);
    for c in &table {
        let line: Vec<String> = c.iter().map(|w| format!("0x{w:04x}")).collect();
        let _ = writeln!(s, "    {},", line.join(", "));
    }
    let _ = writeln!(s, "];\n");
    let n = art::band_count();
    let _ = writeln!(s, "/// Bands of one bar.");
    let _ = writeln!(s, "pub const BAND_COUNT: usize = {n};");
    let _ = writeln!(
        s,
        "/// Plate bands by `[stance][front 0, back 1][band]`: rows `y0..y1` of the bar in this colour."
    );
    let _ = writeln!(s, "pub static BANDS: [[[Band; {n}]; 2]; 2] = [");
    for (front, back, _, _) in stance_colours() {
        let _ = writeln!(s, "    [");
        for t in [front, back] {
            let items: Vec<String> = bands(t)
                .iter()
                .map(|(a, b, c, glass)| {
                    format!(
                        "Band {{ y0: {a}, y1: {b}, rgb: [{}, {}, {}], glass: {glass} }}",
                        c[0], c[1], c[2]
                    )
                })
                .collect();
            let _ = writeln!(s, "        [{}],", items.join(", "));
        }
        let _ = writeln!(s, "    ],");
    }
    let _ = writeln!(s, "];");
    s
}

/// The layout file for `cellcheck --strict`.
pub fn layout() -> String {
    let (ex, ey) = art::EMBLEM_POS;
    let plate_top = art::FRONT_Y;
    let plate_bottom = art::FRONT_Y + art::BAR_H;
    format!(
        "# Generated by showcase-vector/hudart: where the parts of the sprite HUD sit, for cellcheck.\n\
         cols = 0, 160\n\
         y0 = 8\n\
         pitch_y = 40\n\
         levels = 10, 6, 3, 0\n\
         count = {count}\n\
         cell_x0 = {cell_x0}\n\
         pitch = {pitch}\n\
         front_band = {ft}, {fb}\n\
         back_band = 0, {back}\n\
         back_lit = 4\n\
         gem_x0 = {gem_x0}\n\
         gem_band = {gy}, {gy2}\n\
         mirror = emblem_core {cx0} {cy0} {cx1} {cy1}\n\
         mirror = emblem_inner {tx0} {ey} {tx1} {ey2}\n\
         mirror = emblem_bottom {ex} {pb} {ex2} {ey2}\n",
        count = art::COUNT,
        cell_x0 = art::CELL_X0,
        pitch = art::PITCH,
        ft = plate_top,
        fb = plate_bottom,
        back = art::BACK_OFFSET,
        gem_x0 = art::GEM_X0 - 1,
        gy = art::GEM_Y,
        gy2 = art::GEM_Y + art::GEM_H,
        cx0 = ex + 6,
        cy0 = ey + 6,
        cx1 = ex + 18,
        cy1 = ey + 18,
        ex2 = ex + 24,
        tx0 = ex + 5,
        tx1 = ex + 19,
        ey2 = ey + 24,
        pb = plate_bottom,
    )
}
