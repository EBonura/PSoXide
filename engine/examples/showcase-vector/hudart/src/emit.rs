//! Writes the generated Rust data file and the cellcheck layout.

use std::fmt::Write as _;

use crate::art::{
    self, bands, cap_palette, cell_palette, clut, emblem_palette, gem_palette, geos, pack, Tone,
    ATLAS_W, CAP_GLASS, HORIZON, ZENITH,
};
use crate::palette::{mix, WHITE};

/// CLUTs per stance: for each size the lit cell, the empty cell and the bar ends, then the emblem.
pub const CLUTS_PER_STANCE: usize = art::SIZES * 3 + 1;

/// Every CLUT in table order: per stance its sizes and its emblem, then the emblem halfway between
/// the stances, then the two gem CLUTs.
pub fn cluts() -> Vec<[u16; 16]> {
    let mut v = Vec::new();
    for (base, other) in [(HORIZON, ZENITH), (ZENITH, HORIZON)] {
        for g in geos() {
            let t = Tone::at_depth(base, g.depth);
            v.push(clut(&cell_palette(t, true), &[]));
            v.push(clut(&cell_palette(t, false), &[]));
            v.push(clut(&cap_palette(t), &CAP_GLASS));
        }
        v.push(clut(&emblem_palette(base, other), &[]));
    }
    let halfway = mix(HORIZON, ZENITH, 128);
    v.push(clut(
        &emblem_palette(halfway, mix(halfway, WHITE, 170)),
        &[],
    ));
    v.push(clut(&gem_palette(true), &[]));
    v.push(clut(&gem_palette(false), &[]));
    v
}

fn rect_of(name: &str, placed: &[art::Placed]) -> String {
    let p = placed
        .iter()
        .find(|p| p.name == name)
        .expect("sprite in the atlas");
    format!(
        "SpriteRect {{ u: {}, v: {}, w: {}, h: {} }}",
        p.pos.0, p.pos.1, p.sprite.w, p.sprite.h
    )
}

/// The generated data module (to be `include!`d next to the types it uses).
pub fn art_module() -> String {
    let mut s = String::new();
    s.push_str(
        "// @generated by showcase-vector/hudart (`cargo run -p hudart`). Do not edit by hand.\n\n",
    );
    let g = geos();
    let gem_y = art::FRONT_Y + g[0].bar_h() + 1;
    let canvas_w = art::LCAP_X + g[0].width();
    let band_max = g
        .iter()
        .map(|g| bands(g, Tone::at_depth(HORIZON, 0)).len())
        .max()
        .unwrap_or(0);
    for (name, v) in [
        ("COUNT", art::COUNT as i32),
        ("LCAP_X", art::LCAP_X),
        ("BACK_X", art::BACK_X),
        ("LIFT", art::LIFT),
        ("BACK_DROP", art::BACK_DROP),
        ("FRONT_Y", art::FRONT_Y),
        ("EMBLEM_X", art::EMBLEM_POS.0),
        ("EMBLEM_Y", art::EMBLEM_POS.1),
        ("GEM_X0", art::GEM_X0),
        ("GEM_PITCH", art::GEM_PITCH),
        ("GEM_Y", gem_y),
        ("CANVAS_W", canvas_w + art::BACK_X.max(0)),
        ("CANVAS_H", gem_y + art::GEM_H),
    ] {
        let _ = writeln!(s, "pub const {name}: i32 = {v};");
    }
    let _ = writeln!(s, "pub const SIZES: usize = {};", art::SIZES);
    let _ = writeln!(s, "pub const BACK_SIZE: usize = {};", art::BACK_SIZE);
    let _ = writeln!(s, "pub const BAND_MAX: usize = {band_max};");
    let (placed, atlas_h) = pack();
    let atlas = art::atlas_halfwords();
    let _ = writeln!(s, "\npub const ATLAS_HW_W: usize = {};", ATLAS_W / 4);
    let _ = writeln!(s, "pub const ATLAS_H: usize = {atlas_h};");
    let _ = writeln!(
        s,
        "/// 4-bit texels, four per halfword, leftmost in the low nibble."
    );
    let _ = writeln!(s, "pub static ATLAS: [u16; {}] = [", atlas.len());
    for row in atlas.chunks(ATLAS_W / 4) {
        let line: Vec<String> = row.iter().map(|w| format!("0x{w:04x}")).collect();
        let _ = writeln!(s, "    {},", line.join(", "));
    }
    let _ = writeln!(s, "];\n");
    let emblem = rect_of("EMBLEM", &placed);
    let gem = rect_of("GEM", &placed);
    let _ = writeln!(s, "pub const SPRITE_EMBLEM: SpriteRect = {emblem};");
    let _ = writeln!(s, "pub const SPRITE_GEM: SpriteRect = {gem};");
    let _ = writeln!(
        s,
        "\n/// The sizes of the bar, full size first. Positions are relative to the bar's own top-left\n/// corner (its first row, and the HUD column of the left end's first column, `LCAP_X`)."
    );
    let _ = writeln!(s, "pub static GEO: [SizeGeo; SIZES] = [");
    for (i, geo) in g.iter().enumerate() {
        let band_count = bands(geo, Tone::at_depth(HORIZON, 0)).len();
        let _ = writeln!(
            s,
            "    SizeGeo {{ pitch: {}, cell_x0: {}, cell_row: {}, bar_h: {}, bar_x0: {}, cap_x: {}, \
             band_count: {band_count}, cell: {}, cap: {}, lcap: {} }},",
            geo.pitch,
            geo.cell_x0(),
            geo.cell_row(),
            geo.bar_h(),
            geo.bar_x0(),
            geo.cap_x(),
            rect_of(&format!("CELL_{i}"), &placed),
            rect_of(&format!("CAP_{i}"), &placed),
            rect_of(&format!("LCAP_{i}"), &placed),
        );
    }
    let _ = writeln!(s, "];\n");
    let table = cluts();
    let per = CLUTS_PER_STANCE;
    let _ = writeln!(s, "pub const CLUT_COUNT: usize = {};", table.len());
    let _ = writeln!(s, "pub const CLUTS_PER_STANCE: usize = {per};");
    let _ = writeln!(
        s,
        "/// Within a size: the lit cell, the empty cell, the bar ends. Sizes follow each other."
    );
    for (i, name) in ["CLUT_CELL_LIT", "CLUT_CELL_EMPTY", "CLUT_CAP"]
        .iter()
        .enumerate()
    {
        let _ = writeln!(s, "pub const {name}: usize = {i};");
    }
    let _ = writeln!(s, "pub const CLUT_SIZE_STRIDE: usize = 3;");
    let _ = writeln!(s, "pub const CLUT_EMBLEM: usize = {};", art::SIZES * 3);
    let _ = writeln!(s, "pub const CLUT_EMBLEM_HALFWAY: usize = {};", 2 * per);
    let _ = writeln!(s, "pub const CLUT_GEM_LIT: usize = {};", 2 * per + 1);
    let _ = writeln!(s, "pub const CLUT_GEM_EMPTY: usize = {};", 2 * per + 2);
    let _ = writeln!(
        s,
        "/// 15-bit CLUT entries, 16 per CLUT in table order, entry 0 of each transparent."
    );
    let _ = writeln!(s, "pub static CLUTS: [u16; {}] = [", table.len() * 16);
    for c in &table {
        let line: Vec<String> = c.iter().map(|w| format!("0x{w:04x}")).collect();
        let _ = writeln!(s, "    {},", line.join(", "));
    }
    let _ = writeln!(s, "];\n");
    let _ = writeln!(
        s,
        "/// Plate bands by `[stance][size][band]`: rows `y0..y1` of the bar in this colour. A size uses\n/// the first `band_count` entries."
    );
    let _ = writeln!(s, "pub static BANDS: [[[Band; BAND_MAX]; SIZES]; 2] = [");
    for base in [HORIZON, ZENITH] {
        let _ = writeln!(s, "    [");
        for geo in &g {
            let t = Tone::at_depth(base, geo.depth);
            let mut items: Vec<String> = bands(geo, t)
                .iter()
                .map(|(a, b, c, glass)| {
                    format!(
                        "Band {{ y0: {a}, y1: {b}, rgb: [{}, {}, {}], glass: {glass} }}",
                        c[0], c[1], c[2]
                    )
                })
                .collect();
            while items.len() < band_max {
                items.push("Band { y0: 0, y1: 0, rgb: [0, 0, 0], glass: false }".into());
            }
            let _ = writeln!(s, "        [{}],", items.join(", "));
        }
        let _ = writeln!(s, "    ],");
    }
    let _ = writeln!(s, "];");
    s
}

/// The layout file for `cellcheck --strict`: the HUD grid frame (two stances by four levels).
pub fn layout() -> String {
    let (ex, ey) = art::EMBLEM_POS;
    let g = geos();
    let back = &g[art::BACK_SIZE];
    format!(
        "# Generated by showcase-vector/hudart: where the parts of the sprite HUD sit, for cellcheck.\n\
         cols = 0, {canvas_w}\n\
         y0 = 8\n\
         pitch_y = 40\n\
         levels = 10, 6, 3, 0\n\
         count = {count}\n\
         cell_x0 = {cell_x0}\n\
         pitch = {pitch}\n\
         front_band = {ft}, {fb}\n\
         {back_band}\
         back_pitch = {back_pitch}\n\
         back_cell_x0 = {back_cell_x0}\n\
         back_lit = 4\n\
         gem_x0 = {gem_x0}\n\
         gem_pitch = {gem_pitch}\n\
         gem_band = {gy}, {gy2}\n\
         mirror = emblem_core {cx0} {cy0} {cx1} {cy1}\n\
         mirror = emblem {ex} {ey} {ex2} {ey2}\n",
        canvas_w = g[0].width() + art::LCAP_X + art::BACK_X.max(0),
        back_band = {
            let first = art::FRONT_Y - art::LIFT + art::BACK_DROP;
            if first < art::FRONT_Y {
                format!("back_band = {first}, {}\n", art::FRONT_Y)
            } else {
                String::new()
            }
        },
        count = art::COUNT,
        cell_x0 = g[0].strip_x0(),
        pitch = g[0].pitch,
        ft = art::FRONT_Y,
        fb = art::FRONT_Y + g[0].bar_h(),
        back_pitch = back.pitch,
        back_cell_x0 = art::BACK_X + back.strip_x0(),
        gem_x0 = art::GEM_X0 - 1,
        gem_pitch = art::GEM_PITCH,
        gy = art::FRONT_Y + g[0].bar_h() + 1,
        gy2 = art::FRONT_Y + g[0].bar_h() + 1 + art::GEM_H,
        cx0 = ex + 6,
        cy0 = ey + 6,
        cx1 = ex + 18,
        cy1 = ey + 18,
        ex2 = ex + 24,
        ey2 = ey + 24,
    )
}

/// The layout file of one bar size drawn alone in the `hud-sizes` frame: two columns (Horizon and
/// Zenith) of four levels.
pub fn size_layout(size: usize) -> String {
    let g = &geos()[size];
    format!(
        "# Generated by showcase-vector/hudart: one bar of size {size} alone, for cellcheck.\n\
         cols = 0, 160\n\
         y0 = 8\n\
         pitch_y = 40\n\
         levels = 10, 6, 3, 0\n\
         count = {count}\n\
         cell_x0 = {cell_x0}\n\
         pitch = {pitch}\n\
         front_band = 0, {h}\n",
        count = art::COUNT,
        cell_x0 = g.strip_x0(),
        pitch = g.pitch,
        h = g.bar_h(),
    )
}
