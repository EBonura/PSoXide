#[cfg(test)]
mod tests {
    use super::*;

    fn q16(x: f64) -> u32 {
        (x * 65536.0).round() as u32
    }

    #[test]
    fn pitch_table_is_equal_tempered_around_c4() {
        for (i, &v) in PITCH_Q16.iter().enumerate() {
            assert_eq!(v, q16(2f64.powf((i as f64 - 39.0) / 12.0)), "semitone {i}");
        }
        assert_eq!(PITCH_Q16[39], Q16_ONE);
        assert_eq!(PITCH_Q16[51], 2 * Q16_ONE);
    }

    #[test]
    fn bend_tables_span_their_range() {
        assert_eq!(BEND_OCTAVE_Q16[0], Q16_ONE / 2);
        assert_eq!(BEND_OCTAVE_Q16[128], Q16_ONE);
        assert_eq!(BEND_OCTAVE_Q16[255], 2 * Q16_ONE);
        for (i, &v) in BEND_OCTAVE_Q16.iter().enumerate().skip(1) {
            assert_eq!(
                v,
                q16(0.5 * 2f64.powf((i as f64 - 1.0) / 127.0)),
                "octave {i}"
            );
        }
        assert_eq!(BEND_TWO_SEMITONES_Q16[0], BEND_TWO_SEMITONES_Q16[1]);
        assert_eq!(BEND_TWO_SEMITONES_Q16[128], Q16_ONE);
        assert_eq!(BEND_TWO_SEMITONES_Q16[255], q16(2f64.powf(2.0 / 12.0)));
    }

    #[test]
    fn pan_law_is_a_quarter_cosine() {
        assert_eq!(PAN_Q15[0], 32768);
        assert_eq!(PAN_Q15[127], 0);
        // equal power at the centre (index 64 is the cosine of a bit past 45 degrees)
        let (l, r) = (PAN_Q15[64] as u64, PAN_Q15[127 - 64] as u64);
        assert!((l * l + r * r).abs_diff(1 << 30) < (1 << 24));
    }

    #[test]
    fn vibrato_sine_is_one_period_in_64_steps() {
        assert_eq!(VIBRATO_SINE[0], 0);
        assert_eq!(VIBRATO_SINE[16], 32767);
        assert_eq!(VIBRATO_SINE[48], -32767);
        for (i, &v) in VIBRATO_SINE.iter().enumerate() {
            let want = (32767.0 * (core::f64::consts::TAU * i as f64 / 64.0).sin()).trunc() as i16;
            assert_eq!(v, want, "step {i}");
        }
    }

    #[test]
    fn release_steps_fall_with_the_index() {
        // a smaller index is a longer release
        assert!(release_step_q24(1) < release_step_q24(16));
        assert!(release_step_q24(16) < release_step_q24(128));
        assert!(release_step_q24(128) < release_step_q24(250));
        assert!(release_step_q24(250) < release_step_q24(255));
        // 255 releases in under a single update
        assert!(release_step_q24(255) > 1 << 24);
    }

    #[test]
    fn mul_q16_matches_wide_arithmetic() {
        for &(a, b) in &[
            (0u32, 5u32),
            (65536, 65536),
            (123456, 98765),
            (6889, 1_000_000),
            (65535, 131071),
        ] {
            let want = ((a as u64 * b as u64) >> 16) as u32;
            let got = mul_q16(a, b);
            assert!(want.abs_diff(got) <= 2, "{a} * {b}: {want} vs {got}");
        }
    }
}
