//! The Bonnie Studios mark: 128x128 at 4 bits a pixel (4096 sixteen-bit words), stored
//! run-length coded, and its 16-colour palette.
//!
//! Plain, the mark would stay in the executable's RAM image for the whole session for a
//! picture used once, at boot. Coded as below it takes 57 percent of that (4,692 bytes of
//! 8,192) and [`expand`] writes it to VRAM eight rows at a time, so no plain copy exists.
//! A program that never calls `psx_splash::show` links neither.
//!
//! Token byte: `0nnnnnnn` is `n + 1` literal words (little-endian, two bytes each) and
//! `1nnnnnnn` is `n + 3` copies of the one word that follows.

/// Words in the expanded mark.
pub(crate) const WORDS: usize = 4096;

/// FNV-1a over the expanded words' little-endian bytes (the host test pins the mark).
#[cfg(test)]
pub(crate) const FNV1A: u64 = 0xa349_5cc8_751c_b163;

/// The PICO-8 palette the mark was quantised against (RGB555).
pub(crate) const PALETTE: [u16; 16] = [
    0x0000, 0x28a3, 0x288f, 0x2a00, 0x1955, 0x254b, 0x6318, 0x77df, 0x241f, 0x029f, 0x13bf, 0x1b80,
    0x7ea5, 0x4dd0, 0x55df, 0x573f,
];

/// Expand a coded stream into its words. A truncated stream ends early.
pub(crate) fn expand(coded: &[u8]) -> impl Iterator<Item = u16> + '_ {
    let mut at = 0usize;
    let mut run = 0usize;
    let mut literal = 0usize;
    let mut value = 0u16;
    core::iter::from_fn(move || {
        let word = |at: usize| -> Option<u16> {
            Some(u16::from_le_bytes([*coded.get(at)?, *coded.get(at + 1)?]))
        };
        if run > 0 {
            run -= 1;
            return Some(value);
        }
        if literal > 0 {
            literal -= 1;
            let next = word(at)?;
            at += 2;
            return Some(next);
        }
        let token = *coded.get(at)?;
        at += 1;
        if token & 0x80 != 0 {
            value = word(at)?;
            at += 2;
            run = usize::from(token & 0x7f) + 2;
            Some(value)
        } else {
            literal = usize::from(token);
            let next = word(at)?;
            at += 2;
            Some(next)
        }
    })
}

