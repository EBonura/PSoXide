/// Unity in Q16.
pub const Q16_ONE: u32 = 1 << 16;
/// Unity in Q15.
pub const Q15_ONE: u32 = 1 << 15;

/// `a * b` for two Q16 numbers, without a 64-bit intermediate. The result
/// must fit in `u32`.
///
/// ```
/// use psx_seq::tables::mul_q16;
/// assert_eq!(mul_q16(1 << 16, 3 << 15), 3 << 15);
/// assert_eq!(mul_q16(2 << 16, 2 << 16), 4 << 16);
/// ```
pub const fn mul_q16(a: u32, b: u32) -> u32 {
    let (ah, al) = (a >> 16, a & 0xFFFF);
    let (bh, bl) = (b >> 16, b & 0xFFFF);
    (ah * b) + (al * bh) + ((al * bl) >> 16)
}

/// `a * b` for two Q15 numbers (each at most 1.0 or a little more).
pub const fn mul_q15(a: u32, b: u32) -> u32 {
    (a * b) >> 15
}

/// Per-update decrement of a releasing envelope, in Q24 (1.0 = 1 << 24), for
/// release index `idx`. Index 0 never decays on its own. The scale is the
/// number of 60 Hz frames a full-scale level takes to fall to zero, times
/// three updates per frame.
///
/// ```
/// use psx_seq::tables::release_step_q24;
/// assert_eq!(release_step_q24(0), 0);
/// // index 200 is 51 frames: 153 updates
/// assert_eq!(release_step_q24(200), (1u32 << 24) / 153);
/// ```
pub const fn release_step_q24(idx: u8) -> u32 {
    // scale in hundredths of a frame
    let i = idx as u32;
    let scale100: u32 = match idx {
        0 => return 0,
        255 => 25,
        254 => 33,
        253 => 50,
        252 => 66,
        251 => 75,
        128..=250 => (251 - i) * 100,
        16..=127 => 4 * (143 - i) * 100,
        _ => 60 * (23 - i) * 100,
    };
    // 2^24 * 100 / (3 * scale100) with 2^24 * 100 < 2^32
    ((1u32 << 24) * 100) / (3 * scale100)
}

